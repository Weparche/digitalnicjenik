import { expect, test, type Page } from '@playwright/test'
import type { WebsiteCheckDetails, WebsiteCheckResult } from '../shared/website-check'

const complete: WebsiteCheckDetails = { reachable: true, homepageReadable: true, https: true, csvFound: true, xmlFound: true, pricePageFound: true, csvUrl: 'https://salon.hr/cjenik.csv', xmlUrl: 'https://salon.hr/cjenik.xml', publicLinkUrl: 'https://salon.hr/cjenik.csv', archiveFound: true, structureStatus: 'pass', contentStatus: 'pass' }

for (const width of [390, 1440]) {
  test(`per-file analysis shows 20 of 34 named findings without overflow at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    const analysis = { format: 'csv' as const, url: 'https://salon.hr/' + 'dugacki-url-'.repeat(30) + '.csv', fetched: true, structureRecognized: true, itemCount: 34, status: 'warning' as const, structureStatus: 'pass' as const, contentStatus: 'warning' as const, structureReasons: ['Prepoznata struktura. Pronađeno stavki: 34.'], findings: Array.from({ length: 20 }, (_, i) => ({ row: i + 2, itemName: 'Usluga ' + (i + 1), message: 'Nedostaje sidrena cijena.' })), totalFindings: 34 }
    await stub(page, { status: 'yellow', message: 'Potrebna provjera sadržaja.', details: { ...complete, contentStatus: 'warning', csvAnalysis: analysis, xmlAnalysis: { ...analysis, format: 'xml', url: 'https://salon.hr/cjenik.xml', itemCount: 0, structureRecognized: false, status: 'unknown', structureStatus: 'unknown', contentStatus: 'unknown', findings: [], totalFindings: 0 } } })
    await page.goto('/')
    await page.getByLabel('Adresa web stranice', { exact: true }).fill('salon.hr')
    await page.getByRole('button', { name: 'Provjeri besplatno' }).click()
    const csvPanel = page.getByRole('article', { name: 'CSV analiza' })
    await expect(csvPanel).toContainText('20 od 34')
    await expect(csvPanel.locator('li')).toHaveCount(20)
    await expect(csvPanel).toContainText('„Usluga 20”')
    await expect(page.getByRole('article', { name: 'XML analiza' })).toContainText('Sadržaj nije moguće potvrditi')
    await csvPanel.scrollIntoViewIfNeeded()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    await page.screenshot({ path: `.tmp-review/checker-${width}.png`, fullPage: false })
  })
}
async function stub(page: Page, result: WebsiteCheckResult) {
  await page.route('**/api/public-config', (r) => r.fulfill({ json: { turnstileSiteKey: '' } }))
  await page.route('**/api/digitalni-cjenik/check', (r) => r.fulfill({ json: result }))
}

for (const width of [1440, 768, 390]) {
  test(`checker, trust and platforms fit first viewport at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await expect(page.getByRole('heading', { level: 1 })).toHaveText(/Imate web\s*stranicu\?\s*Provjerite\s*digitalni cjenik\s*besplatno\./)
    const button = page.getByRole('button', { name: 'Provjeri besplatno' })
    await expect(button).toBeVisible()
    expect((await button.boundingBox())!.y + (await button.boundingBox())!.height).toBeLessThan(900)
    const trust = await page.locator('.acq-trust').boundingBox()
    expect(trust!.y + trust!.height).toBeLessThan(900)
    await expect(page.locator('.acq-hero .ew-pills')).toBeVisible()
    await expect(page.locator('.acq-hero-platforms')).toContainText('od 19,90 €/god')
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    await expect(page.locator('.acq-plans')).toHaveCount(1)
    await expect(page.locator('.acq-plans')).toContainText('19,90 €')
    await expect(page.locator('.acq-plan').first().locator('.acq-plan-highlight')).toHaveText('Do 5.000 stavki')
    await expect(page.locator('.education-cta')).toHaveCount(0)
    expect(await page.locator('main').count()).toBe(1)
    if (width === 1440) {
      const dimensions = await page.locator('.acq-photo img').evaluate((el) => { const img = el as HTMLImageElement; const r = img.getBoundingClientRect(); return { ratio: r.width / r.height, naturalRatio: img.naturalWidth / img.naturalHeight, x: r.x, right: r.right } })
      expect(dimensions.ratio).toBeCloseTo(dimensions.naturalRatio, 2)
      expect(dimensions.x).toBeGreaterThan(0)
      expect(dimensions.right).toBeLessThan(width)
    }
    const content = await page.locator('.acq-content').boundingBox()
    const deadline = await page.locator('.acq-deadline').boundingBox()
    expect(deadline!.x).toBeGreaterThanOrEqual(content!.x)
    expect(deadline!.x + deadline!.width).toBeLessThanOrEqual(content!.x + content!.width)
    await page.evaluate(() => window.scrollTo(0, 1600))
    await expect.poll(async () => (await page.locator('.acq-header-bar').boundingBox())!.y).toBe(0)
    await expect(page.locator('.acq-deadline')).toBeInViewport()
  })
}

test('invalid input focuses field; bare domain normalizes; result has nine evidence disclosures', async ({ page }) => {
  await stub(page, { status: 'green', message: 'Pronađena je javna datoteka.', details: complete })
  await page.goto('/')
  await page.getByRole('button', { name: 'Provjeri besplatno' }).click()
  await expect(page.getByRole('alert')).toContainText('Unesite ispravnu adresu')
  await expect(page.getByLabel('Adresa web stranice', { exact: true })).toBeFocused()
  await expect(page.locator('#acq-url')).toHaveCSS('outline-style', 'none')
  await expect(page.locator('.acq-input')).toHaveCSS('outline-width', '2px')
  await page.getByLabel('Adresa web stranice', { exact: true }).fill('salon.hr')
  const request = page.waitForRequest('**/api/digitalni-cjenik/check')
  await page.getByLabel('Adresa web stranice', { exact: true }).press('Enter')
  expect((await request).postDataJSON()).toEqual({ url: 'https://salon.hr/' })
  await expect(page.locator('.acq-result-summary')).toHaveText('9/9 tehničkih provjera prolazi')
  await expect(page.locator('.acq-tone-green')).toBeVisible()
  await expect(page.locator('.acq-result-anchor')).toBeFocused()
  await expect(page.locator('.acq-result-anchor')).toHaveCSS('outline-style', 'none')
  await page.keyboard.press('Tab')
  await expect(page.locator('.acq-status-list summary').first()).toBeFocused()
  await expect(page.locator('.acq-status-list summary').first()).toHaveCSS('outline-style', 'solid')
  await expect(page.locator('.acq-status-list summary')).toHaveCount(9)
  await page.locator('.acq-status-list summary').nth(3).click()
  await expect(page.locator('.acq-status-list > li').nth(3).getByRole('link')).toHaveAttribute('href', 'https://salon.hr/cjenik.csv')
  await expect(page.locator('.acq-status-list > li').nth(3).getByRole('link')).toBeVisible()
})

test('one supported format does not reduce the score and context reaches Web Link inquiry', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await stub(page, { status: 'green', message: 'Pronađena je CSV datoteka.', details: { ...complete, xmlFound: false, xmlUrl: null, archiveFound: false, contentStatus: 'unknown' } })
  await page.goto('/')
  await page.getByLabel('Adresa web stranice', { exact: true }).fill('salon.hr')
  await page.getByRole('button', { name: 'Provjeri besplatno' }).click()
  await expect(page.locator('.acq-result-summary')).toContainText('7/9')
  await expect(page.locator('.acq-result-anchor')).toBeFocused()
  await expect(page.locator('.acq-tone-yellow')).toBeVisible()
  // Content and the archive are unconfirmed; an archive that cannot be confirmed is not reported as missing.
  await expect(page.locator('.acq-status-unknown')).toHaveCount(2)
  await expect(page.locator('.acq-status-missing')).toHaveCount(0)
  await expect(page.locator('.acq-plans')).toContainText('19,90 €')
  await expect(page.locator('.acq-plans')).toContainText('49,90 €')
  await expect(page.locator('.acq-plans')).toContainText('79,90 €')
  const resolve = page.getByRole('link', { name: 'Riješite digitalni cjenik' })
  await expect(resolve).toHaveCSS('background-color', 'rgb(6, 96, 255)')
  expect((await resolve.boundingBox())!.height).toBeGreaterThanOrEqual(56)
  await resolve.click()
  await expect(page).toHaveURL(/#rjesenja$/)
  const header = await page.locator('.acq-header-bar').boundingBox()
  const solutions = await page.getByRole('heading', { name: 'Trebate riješiti digitalni cjenik?' }).boundingBox()
  expect(solutions!.y).toBeGreaterThanOrEqual(header!.y + header!.height)
  await page.getByRole('button', { name: 'Odaberi Web Link', exact: true }).click()
  await expect(page.locator('.lead-section')).toBeFocused()
  await expect(page.locator('.lead-section')).toHaveCSS('outline-style', 'none')
  await expect(page.getByRole('heading', { name: 'Zatražite paket Web Link' })).toBeVisible()
  await expect(page.locator('.lead-price')).toContainText('19,90 €/god')
  await expect(page.locator('.lead-form input[name="website"]')).toHaveValue('https://salon.hr/')
  await expect(page.locator('.lead-context')).toContainText('7/9')
  await expect(page.locator('.lead-context')).toContainText('https://salon.hr/cjenik.csv')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

